# -*- coding: utf-8 -*-
"""Собирает .docx-сообщение об Эрихе Фромме (~1,5 стр. A4)."""
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, Cm, RGBColor

ACCENT = RGBColor(0x1F, 0x4E, 0x79)   # тёмно-синий для заголовков
GREY = RGBColor(0x59, 0x59, 0x59)

doc = Document()

# --- настройки страницы и стиля по умолчанию ---
sec = doc.sections[0]
sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
sec.top_margin = sec.bottom_margin = Cm(2.0)
sec.left_margin = sec.right_margin = Cm(2.2)

normal = doc.styles["Normal"]
normal.font.name = "Times New Roman"
normal.font.size = Pt(12)
normal.paragraph_format.space_after = Pt(6)
normal.paragraph_format.line_spacing = 1.15

# чтобы кириллица точно применилась и к east-asian шрифту
from docx.oxml.ns import qn
normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def title(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(17)
    r.font.color.rgb = ACCENT
    p.paragraph_format.space_after = Pt(2)
    return p


def subtitle(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.italic = True
    r.font.size = Pt(10.5)
    r.font.color.rgb = GREY
    p.paragraph_format.space_after = Pt(12)
    return p


def heading(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(12.5)
    r.font.color.rgb = ACCENT
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(4)
    return p


def para(text):
    p = doc.add_paragraph(text)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Cm(1.0)
    return p


def fact(num, lead, text):
    """Нумерованный факт: жирный заголовок-крючок + одно-два пояснения."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.left_indent = Cm(0.7)
    p.paragraph_format.space_after = Pt(5)
    r1 = p.add_run(f"{num}. {lead} ")
    r1.bold = True
    r1.font.color.rgb = ACCENT
    p.add_run(text)
    return p


def epigraph(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.italic = True
    r.font.size = Pt(11)
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(2)
    return p


# ------------------------------------------------------------------ СОДЕРЖАНИЕ
title("Эрих Фромм")
subtitle("психолог, который учил свободе и любви  •  1900–1980")

para(
    "Эрих Фромм — немецко-американский психолог и философ. Он первым соединил психоанализ "
    "Фрейда с социологией и задал простой, но неудобный вопрос: почему человек, получив "
    "свободу, так часто от неё убегает? Его книги читают уже семьдесят лет — потому что они "
    "не про пациентов на кушетке, а про каждого из нас."
)

# --- детство -----------------------------------------------------------------
heading("Детство: тревожный дом и один большой вопрос")
para(
    "Фромм родился 23 марта 1900 года во Франкфурте-на-Майне, единственным ребёнком в "
    "ортодоксальной еврейской семье. Отец, Нафтали, торговал вином и строго соблюдал традиции; "
    "мать, Роза, мечтала, что сын станет музыкантом. Дед и прадед были раввинами, и родные "
    "видели в нём продолжателя династии. Сам Фромм позже вспоминал: «Я был единственным "
    "ребёнком у двух очень тревожных родителей». Он учил латынь, играл на фортепиано, читал "
    "Талмуд — и любил пророков, а не рассказы о битвах."
)
para(
    "В четырнадцать лет грянула Первая мировая. Эрих не мог понять, что заставляет миллионы "
    "людей убивать друг друга. Этот вопрос стал делом его жизни: почему разумное существо так "
    "легко подчиняется и разрушает?"
)

# --- становление -------------------------------------------------------------
heading("Как он стал учёным")
para(
    "В 1918 году он поступил на юриспруденцию во Франкфуртский университет, но через два "
    "семестра понял: не его. Перевёлся в Гейдельберг — социология, психология, философия. "
    "В 1922 году защитил докторскую о еврейском законе и жизни диаспоры под руководством "
    "Альфреда Вебера, младшего брата знаменитого Макса Вебера. Затем — психоанализ во "
    "Франкфурте и Берлине. С 1930 года Фромм заведует отделом социальной психологии в "
    "Институте социальных исследований; после прихода нацистов уезжает — Женева, Нью-Йорк, "
    "Колумбийский университет."
)

# --- семья -------------------------------------------------------------------
heading("Семья: три брака и двадцать семь лет с Аннис")
para(
    "Первой женой в 1926 году стала Фрида Фромм-Райхман — психоаналитик на десять лет старше и "
    "его собственный терапевт. Брак распался, но они остались друзьями и коллегами. Второй "
    "женой в 1944 году стала фотограф Хенни Гурланд; ради её здоровья супруги в 1950 году "
    "перебрались в Мексику, где она вскоре умерла. Третья жена, американка Аннис Фриман, "
    "прожила с Фроммом двадцать семь лет. Своих детей не было, зато он дружил с пасынком "
    "Джозефом и всю жизнь пел хасидские песни — музыка оставалась его отдушиной."
)

# --- факты -------------------------------------------------------------------
heading("Десять интересных фактов — по порядку")

fact(1, "Прогноз, который сбылся.",
     "В 1932 году Фромм провёл опрос немецких рабочих и служащих и пришёл к невесёлому выводу: "
     "серьёзного сопротивления Гитлеру не будет. Через год так и вышло — вывод оказался "
     "пугающе точным.")
fact(2, "Бегство от свободы.",
     "В 1941 году вышла его самая знаменитая книга. Фромм показал: свобода тяжела, и от неё "
     "убегают тремя путями — в подчинение сильному, в разрушение и в «конформизм автомата», "
     "когда человек просто становится как все.")
fact(3, "Любовь — это навык, а не подарок судьбы.",
     "«Искусство любить» (1956) разошлось миллионами экземпляров. Формула Фромма проста: "
     "забота, ответственность, уважение и знание. Любить — значит трудиться, а не «ждать "
     "чувства».")
fact(4, "Аналитик без медицинского диплома.",
     "Фромм был социологом по образованию: врачом он не стал никогда. За это ортодоксальные "
     "фрейдисты считали его чужаком и в конце концов отстранили от обучения студентов.")
fact(5, "Дзен на кушетке.",
     "После смерти второй жены он увлёкся мистикой и в 1960 году вместе с японским философом "
     "Д. Т. Судзуки выпустил книгу «Дзен-буддизм и психоанализ» — редкий для того времени "
     "диалог Востока и Запада.")
fact(6, "Иметь или быть?",
     "Одноимённая книга 1976 года — его духовное завещание. Два способа жить: копить и владеть "
     "или же раскрываться и действовать. Задолго до слов «общество потребления» Фромм описал "
     "усталость от покупок, которая не лечится покупками.")
fact(7, "Человек как товар.",
     "Фромм придумал термин «маркетинговая личность»: в рыночном мире мы продаём самих себя, "
     "как упаковку на полке, и ценим себя по цене спроса. Термину семьдесят лет, а звучит "
     "будто про соцсети.")
fact(8, "Биофилия против некрофилии.",
     "Любовь к живому против тяги к мёртвому, машинному, неживому. По Фромму, это и есть "
     "главный выбор человека — тихий, ежедневный, без громких лозунгов.")
fact(9, "Учёный на баррикадах.",
     "В 1957 году он стал сооснователем движения за разумную ядерную политику, открыто выступал "
     "против войны во Вьетнаме. В 1966 году его назвали «Гуманистом года», а в 1979-м он "
     "получил премию Нелли Закс.")
fact(10, "Мексика и финал.",
     "С 1949 года — профессор Национального университета Мексики, основатель и директор "
     "Мексиканского института психоанализа до 1976 года. Фромм перенёс четыре инфаркта и всё "
     "равно работал: умер он 18 марта 1980 года в швейцарском Муральто — за пять дней до "
     "80-летия и до выхода своего десятитомника.")

# --- финал -------------------------------------------------------------------
heading("Что осталось")
para(
    "Фромм верил: главная задача человека — «родить себя самому», стать собой, а не удобной "
    "копией всех остальных. Свобода пугает, любовь требует труда, но именно в этом труде и "
    "спрятано взрослое счастье. Мальчик из винной лавки во Франкфурте ответил на свой детский "
    "вопрос так: люди разрушают, когда не умеют любить, — а значит, любить можно научиться."
)

epigraph("«Любовь — это не отношение к одному человеку, это установка по отношению "
         "ко всему миру».")
p = doc.paragraphs[-1]
p.paragraph_format.space_after = Pt(10)

doc.core_properties.title = "Эрих Фромм — сообщение"
doc.core_properties.subject = "Биография, семья и интересные факты"

doc.save("Эрих_Фромм.docx")
print("saved")
