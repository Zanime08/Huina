-- 1. Документы и их авторы
--    Соединение четырёх таблиц; фамилия и инициалы автора склеиваются в одно поле.
SELECT [Данные документов].[Название],
       [Авторы].[Фамилия] & " " & [Авторы].[Инициалы] AS Автор,
       [Авторы документов].[Позиция автора],
       [Данные документов].[Год издания],
       [Издательства].[Издательство]
FROM Издательства
     INNER JOIN (([Данные документов]
        INNER JOIN [Авторы документов]
           ON [Данные документов].[ID документа] = [Авторы документов].[ID документа])
        INNER JOIN Авторы
           ON [Авторы документов].[ID автора] = [Авторы].[ID автора])
     ON [Издательства].[ID издательства] = [Данные документов].[ID издательства]
ORDER BY [Данные документов].[Название], [Авторы документов].[Позиция автора];


-- 2. Поиск документов по типу (запрос с параметром)
--    При открытии Access спросит «Введите тип документа»; поиск по части слова
--    (например: учебник, статья, пособие). Пустой ввод — все документы.
PARAMETERS [Введите тип документа] Text ( 255 );
SELECT [Данные документов].[Название],
       [Типы документов].[Тип],
       [Данные документов].[Год издания],
       [Язык].[Язык],
       [Данные документов].[Количество страниц]
FROM Язык
     INNER JOIN ([Типы документов]
        INNER JOIN [Данные документов]
           ON [Типы документов].[ID типа] = [Данные документов].[ID типа])
     ON [Язык].[ID языка] = [Данные документов].[ID языка]
WHERE [Типы документов].[Тип] Like "*" & [Введите тип документа] & "*"
ORDER BY [Данные документов].[Год издания] DESC;


-- 3. Количество документов по издательствам (итоговый запрос)
--    Группировка, Count и Sum; сортировка по убыванию количества.
SELECT [Издательства].[Издательство],
       Count([Данные документов].[ID документа]) AS [Количество документов],
       Sum([Данные документов].[Количество страниц]) AS [Всего страниц]
FROM Издательства
     INNER JOIN [Данные документов]
        ON [Издательства].[ID издательства] = [Данные документов].[ID издательства]
GROUP BY [Издательства].[Издательство]
ORDER BY Count([Данные документов].[ID документа]) DESC, [Издательства].[Издательство];


-- 4. Издания после 2010 года (запрос с условием отбора)
SELECT [Данные документов].[Название],
       [Данные документов].[Год издания],
       [Издательства].[Издательство],
       [Типы документов].[Тип],
       [Данные документов].[Гиперссылка источника]
FROM [Типы документов]
     INNER JOIN (Издательства
        INNER JOIN [Данные документов]
           ON [Издательства].[ID издательства] = [Данные документов].[ID издательства])
     ON [Типы документов].[ID типа] = [Данные документов].[ID типа]
WHERE [Данные документов].[Год издания] >= 2010
ORDER BY [Данные документов].[Год издания] DESC, [Данные документов].[Название];


-- 5. Статистика публикаций по авторам
--    Внешнее соединение (LEFT JOIN): авторы без организации тоже попадают в отчёт.
SELECT [Авторы].[Фамилия],
       [Авторы].[Инициалы],
       [Организации].[Название] AS Организация,
       Count([Авторы документов].[ID документа]) AS [Число публикаций]
FROM (Авторы
     INNER JOIN [Авторы документов]
        ON [Авторы].[ID автора] = [Авторы документов].[ID автора])
     LEFT JOIN Организации
        ON [Авторы].[ID организации] = [Организации].[ID организации]
GROUP BY [Авторы].[Фамилия], [Авторы].[Инициалы], [Организации].[Название]
ORDER BY Count([Авторы документов].[ID документа]) DESC, [Авторы].[Фамилия];
