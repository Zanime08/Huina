def create_schema(db):
    T, L, M, D = DataType.TEXT, DataType.LONG, DataType.MEMO, DataType.SHORT_DATE_TIME

    (TableBuilder("Язык")
     .addColumn(col("ID языка", L, autonum=True, desc="Используется для связи с таблицей Данные документов."))
     .addColumn(col("Язык", T, 50, required=True, desc="Обязательное поле."))
     .setPrimaryKey("ID языка").toTable(db))

    (TableBuilder("Типы документов")
     .addColumn(col("ID типа", L, autonum=True, desc="Используется для связи с таблицей Данные документов."))
     .addColumn(col("Тип", T, 100, required=True,
                    desc="Обязательное поле. Названия типов взяты из методических разработок и стандартов."))
     .addColumn(col("Комментарий", M, desc="Комментарий к типу документа. Выводится в формах и запросах."))
     .setPrimaryKey("ID типа").toTable(db))

    (TableBuilder("Организации")
     .addColumn(col("ID организации", L, autonum=True, desc="Используется для связи с таблицей Авторы."))
     .addColumn(col("Название", T, 255, required=True, desc="Обязательное поле."))
     .addColumn(col("Адрес", T, 255, desc="Почтовый адрес, e-mail или сайт организации."))
     .addColumn(col("Комментарий", M, desc="Комментарий к организации. Выводится в формах и запросах."))
     .setPrimaryKey("ID организации").toTable(db))

    (TableBuilder("Издательства")
     .addColumn(col("ID издательства", L, autonum=True, desc="Используется для связи с таблицей Данные документов."))
     .addColumn(col("Издательство", T, 100, required=True,
                    desc="Обязательное поле. Сокращение города и название издательства (как в библиографической ссылке)."))
     .addColumn(col("Адрес", T, 255, desc="Адрес издательства, e-mail или сайт."))
     .addColumn(col("Телефон", T, 50, desc="Контактные телефоны издательства."))
     .addColumn(col("Комментарий", M, desc="Комментарий к издательству. Выводится в формах и запросах."))
     .setPrimaryKey("ID издательства").toTable(db))

    (TableBuilder("Владельцы")
     .addColumn(col("ID владельца", L, autonum=True, desc="Используется для связи с таблицей Данные документов."))
     .addColumn(col("Авторское право", T, 255, required=True,
                    desc="Описывает группы владельцев документов: авторы, издательства и др."))
     .setPrimaryKey("ID владельца").toTable(db))

    (TableBuilder("Редакторы")
     .addColumn(col("ID редактора", L, autonum=True, desc="Используется для связи с таблицей Данные документов."))
     .addColumn(col("Инициалы", T, 4, desc="Размер поля ограничен четырьмя знаками."))
     .addColumn(col("Фамилия", T, 50, required=True, desc="Обязательное поле."))
     .addColumn(col("Имя", T, 50, desc="Необязательное поле."))
     .addColumn(col("Отчество", T, 50, desc="Необязательное поле."))
     .addColumn(col("Комментарий", M, desc="Комментарий к редактору. Выводится в формах и запросах."))
     .setPrimaryKey("ID редактора").toTable(db))

    (TableBuilder("Авторы")
     .addColumn(col("ID автора", L, autonum=True, desc="Используется для связи с таблицей Авторы документов."))
     .addColumn(col("Инициалы", T, 4, desc="Размер поля ограничен четырьмя знаками."))
     .addColumn(col("Фамилия", T, 50, required=True, desc="Обязательное поле."))
     .addColumn(col("Имя", T, 50, desc="Необязательное поле."))
     .addColumn(col("Отчество", T, 50, desc="Необязательное поле."))
     .addColumn(col("ID организации", L, desc="Используется для связи с таблицей Организации."))
     .addColumn(col("Комментарий", M, desc="Комментарий к автору. Выводится в формах и запросах."))
     .setPrimaryKey("ID автора").toTable(db))

    (TableBuilder("Данные документов")
     .addColumn(col("ID документа", L, autonum=True,
                    desc="Используется в связях с таблицей Авторы документов (неявно Редакторы)."))
     .addColumn(col("Дата", D, default="Date()",
                    desc="Дата внесения записи. Значение по умолчанию — функция Date()."))
     .addColumn(col("Название", T, 255, required=True, desc="Обязательное поле."))
     .addColumn(col("ID типа", L, desc="Используется для связи с таблицей Типы документов."))
     .addColumn(col("Год издания", L, desc="Год создания электронного документа."))
     .addColumn(col("ID издательства", L, desc="Используется для связи с таблицей Издательства."))
     .addColumn(col("Переход к источнику", T, 255,
                    desc="Файл электронного документа (в учебнике — поле типа «Вложение»; здесь хранится имя файла)."))
     .addColumn(col("Гиперссылка источника", M, hyperlink=True,
                    desc="Гиперссылка к файлу электронного документа или к его источнику в сети."))
     .addColumn(col("ID редактора", L, desc="Используется для связи с таблицей Редакторы."))
     .addColumn(col("ID языка", L, desc="Используется для связи с таблицей Язык."))
     .addColumn(col("Количество страниц", L, desc="Количество страниц в электронном документе."))
     .addColumn(col("Количество рисунков", L, desc="Количество рисунков. Необязательное поле."))
     .addColumn(col("Количество ссылок", L, desc="Количество ссылок на литературные источники. Необязательное поле."))
     .addColumn(col("Твердая копия", M,
                    desc="Место хранения и инвентарный номер твёрдой копии документа. Необязательное поле."))
     .addColumn(col("Комментарий", M, desc="Комментарий к документу. Выводится в формах и запросах."))
     .addColumn(col("ID владельца", L, desc="Используется для связи с таблицей Владельцы."))
     .setPrimaryKey("ID документа").toTable(db))

    (TableBuilder("Авторы документов")
     .addColumn(col("ID документа", L, desc="Для связи с таблицей Данные документов."))
     .addColumn(col("ID автора", L, desc="Для связи с таблицей Авторы."))
     .addColumn(col("Позиция автора", L, default="1",
                    desc="Позиция автора в авторском списке. По умолчанию 1."))
     .setPrimaryKey("ID документа", "ID автора").toTable(db))

    # Связи «один-ко-многим» с обеспечением целостности данных (+ каскадное обновление)
    rels = [
        ("Язык", "ID языка", "Данные документов", "ID языка"),
        ("Типы документов", "ID типа", "Данные документов", "ID типа"),
        ("Издательства", "ID издательства", "Данные документов", "ID издательства"),
        ("Редакторы", "ID редактора", "Данные документов", "ID редактора"),
        ("Владельцы", "ID владельца", "Данные документов", "ID владельца"),
        ("Организации", "ID организации", "Авторы", "ID организации"),
        ("Данные документов", "ID документа", "Авторы документов", "ID документа"),
        ("Авторы", "ID автора", "Авторы документов", "ID автора"),
    ]
    for ft, fc, tt, tc in rels:
        (RelationshipBuilder(ft, tt).addColumns(fc, tc)
         .setReferentialIntegrity().setCascadeUpdates().toRelationship(db))


