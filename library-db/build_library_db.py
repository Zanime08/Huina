def jbytes(b: bytes):
    return JBytes(list(struct.unpack(f"{len(b)}b", b)))


def jdate(y, m, d):
    ts = dt.datetime(y, m, d, 12, 0, 0, tzinfo=dt.timezone.utc).timestamp()
    return JDate(int(ts * 1000))


REQ = PropertyMap.REQUIRED_PROP
DEF = PropertyMap.DEFAULT_VALUE_PROP
DESC = PropertyMap.DESCRIPTION_PROP


def col(name, dtype, length=None, required=False, default=None, desc=None, autonum=False, hyperlink=False):
    c = ColumnBuilder(name, dtype)
    if length is not None:
        c.setLengthInUnits(length)
    if autonum:
        c.setAutoNumber(True)
    if hyperlink:
        c.setHyperlink(True)
    if required:
        c.putProperty(REQ, True)
    if default is not None:
        c.putProperty(DEF, default)
    if desc:
        c.putProperty(DESC, desc)
    return c


