def add_select_query(db, name, tables, columns, joins=(), where=None, groupby=(),
                     orderby=(), params=(), select_flag=0):
    """Создаёт сохранённый запрос на выборку так же, как это делает Access:
    строка в MSysObjects (Type=5), права в MSysACEs и описание в MSysQueries."""
    so = db.getSystemTable("MSysObjects")
    sq = db.getSystemTable("MSysQueries")
    ac = db.getSystemTable("MSysACEs")
    rows = list(so)
    ids = [int(r.get("Id")) for r in rows]
    parent = [int(r.get("Id")) for r in rows
              if r.get("Name") == "Tables" and int(r.get("Type")) == 3 and int(r.get("ParentId")) == 0xF000000][0]
    owner = [r.get("Owner") for r in rows
             if int(r.get("Type")) == 1 and not str(r.get("Name")).startswith("MSys")][0]
    new_id = max(i for i in ids if i < 0) + 1
    assert new_id < 0 and new_id not in ids
    now = JDate()
    cat = {"Id": new_id, "ParentId": parent, "Name": name, "Type": 5,
           "DateCreate": now, "DateUpdate": now, "Owner": owner, "Flags": 0}
    so.addRow(*[cat.get(c.getName()) for c in so.getColumns()])
    for sid in [r.get("SID") for r in ac if int(r.get("ObjectId")) == parent]:
        ace = {"ObjectId": new_id, "SID": sid, "ACM": 1048575, "FInheritable": False}
        ac.addRow(*[ace.get(c.getName()) for c in ac.getColumns()])

    qrows = []

    def row(attr, order=1, name1=None, name2=None, expr=None, flag=None, extra=None):
        qrows.append({"ObjectId": new_id, "Attribute": attr, "Order": jbytes(struct.pack(">i", order)),
                      "Name1": name1, "Name2": name2, "Expression": expr, "Flag": flag, "LvExtra": extra})

    row(0, flag=0)                     # начало описания
    row(255)                           # конец описания
    row(1, flag=1)                     # тип запроса: SELECT
    for i, p in enumerate(params, 1):  # параметры (тип Text)
        row(2, i, name1=p, flag=10)
    row(3, flag=select_flag)           # флаги SELECT (0 — обычный, 2 — DISTINCT)
    for i, t in enumerate(tables, 1):  # таблицы
        row(5, i, name1=t)
    for i, c in enumerate(columns, 1):  # столбцы (выражение, псевдоним)
        expr, alias = c if isinstance(c, tuple) else (c, None)
        row(6, i, name1=alias, expr=expr, flag=0)
    for i, j in enumerate(joins, 1):   # соединения: (таблица1, таблица2, условие, тип 1/2/3)
        row(7, i, name1=j[0], name2=j[1], expr=j[2], flag=j[3])
    if where:
        row(8, expr=where)
    for i, g in enumerate(groupby, 1):
        row(9, i, expr=g, flag=0)
    for i, o in enumerate(orderby, 1):
        expr, desc = o if isinstance(o, tuple) else (o, False)
        row(11, i, name1=("D" if desc else None), expr=expr)
    cols = [c.getName() for c in sq.getColumns()]
    for r in qrows:
        sq.addRow(*[r.get(c) for c in cols])
    return new_id


