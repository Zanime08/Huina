def set_font(run, size=14, bold=False, italic=False, color=None):
    f = run.font
    f.name = "Times New Roman"
    f.size = Pt(size)
    f.bold = bold
    f.italic = italic
    if color:
        f.color.rgb = color
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def para(text="", size=14, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.LEFT,
         space_before=0, space_after=0, indent=0, color=None):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.15
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.first_line_indent = Cm(indent)
    if text:
        set_font(p.add_run(text), size, bold, italic, color)
    return p


