def set_font(run, size=14, bold=False, italic=False, name="Times New Roman"):
    f = run.font
    f.name = name
    f.size = Pt(size)
    f.bold = bold
    f.italic = italic
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def para(text="", size=14, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         indent=Cm(1.25), space_before=0, space_after=0):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.first_line_indent = Cm(indent)
    if text:
        set_font(p.add_run(text), size, bold, italic)
    return p


def heading(text, size=15, space_before=12, centered=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if centered else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.first_line_indent = Cm(0)
    set_font(p.add_run(text), size, bold=True)
    return p


def bullets(items, size=14):
    for it in items:
        head, body = it if isinstance(it, tuple) else (it, None)
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.5
        set_font(p.add_run("– "), size)
        set_font(p.add_run(head), size, bold=True)
        if body:
            set_font(p.add_run(" " + body), size)


def numbered(items, size=14, style="num"):
    for i, it in enumerate(items, 1):
        head, body = it if isinstance(it, tuple) else (it, None)
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.5
        set_font(p.add_run(f"{i}) " if style == "num" else "– "), size)
        set_font(p.add_run(head), size, bold=True)
        if body:
            set_font(p.add_run(" " + body), size)


def shade(cell, color="D9E2F3"):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), color)
    tcPr.append(sh)


def make_table(rows, widths=None, header=True, size=12, caption=None):
    if caption:
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_after = Pt(4)
        set_font(p.add_run(caption), 13, bold=True)
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.text = ""
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_after = Pt(0)
            set_font(p.add_run(str(val)), size, bold=(header and ri == 0))
            if header and ri == 0:
                shade(cell)
    if widths:
        for ri in range(len(rows)):
            for ci, w in enumerate(widths):
                t.cell(ri, ci).width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


