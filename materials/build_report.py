def set_font(run, size=14, bold=False, italic=False, name="Times New Roman"):
    f = run.font
    f.name = name
    f.size = Pt(size)
    f.bold = bold
    f.italic = italic
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def para(text="", size=14, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
         indent=Cm(1.25), space_before=0, space_after=0, style=None, centered_no_indent=False):
    p = doc.add_paragraph(style=style)
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.first_line_indent = Cm(0.0) if centered_no_indent else Cm(indent)
    if text:
        r = p.add_run(text)
        set_font(r, size, bold, italic)
    return p


def heading(text, size=16, space_before=12, centered=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if centered else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(text)
    set_font(r, size, bold=True)
    return p


def bullets(items, size=14):
    for it in items:
        if isinstance(it, tuple):
            head, body = it
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.first_line_indent = Cm(1.25)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.5
            r = p.add_run("– ")
            set_font(r, size)
            r = p.add_run(head)
            set_font(r, size, bold=True)
            if body:
                r = p.add_run(" " + body)
                set_font(r, size)
        else:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            p.paragraph_format.left_indent = Cm(1.25)
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.5
