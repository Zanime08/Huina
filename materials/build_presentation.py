def box(slide, x, y, w, h, fill=None, line=None, lw=1.0):
    from pptx.enum.shapes import MSO_SHAPE
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, x, y, w, h)
    sh.adjustments[0] = 0.04
    if fill is None:
        sh.fill.background()
    else:
        sh.fill.solid(); sh.fill.fore_color.rgb = fill
    if line is None:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = line; sh.line.width = Pt(lw)
    sh.shadow.inherit = False
    return sh


def rect(slide, x, y, w, h, fill):
    from pptx.enum.shapes import MSO_SHAPE
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    sh.fill.solid(); sh.fill.fore_color.rgb = fill
    sh.line.fill.background(); sh.shadow.inherit = False
    return sh


def text(slide, x, y, w, h, runs, size=18, bold=False, color=RGBColor(0x22, 0x22, 0x22),
         align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, space_after=6, line_spacing=1.05):
    """runs: строка или список (текст, размер, жирный, цвет, отступ_слева)"""
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = Inches(0.05)
    tf.margin_top = tf.margin_bottom = 0
    if isinstance(runs, str):
        runs = [runs]
    first = True
    for r in runs:
        if isinstance(r, str):
            t, sz, bd, cl, ind = r, size, bold, color, 0
        else:
            t = r[0]
            sz = r[1] if len(r) > 1 else size
            bd = r[2] if len(r) > 2 else bold
            cl = r[3] if len(r) > 3 and r[3] is not None else color
            ind = r[4] if len(r) > 4 else 0
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.alignment = align
        p.space_after = Pt(space_after)
        p.line_spacing = line_spacing
        if ind:
            p.level = ind
        run = p.add_run(); run.text = t
        f = run.font
        f.name = "Calibri"; f.size = Pt(sz); f.bold = bd; f.color.rgb = cl
    return tb


def picture_fit(slide, name, x, y, w, h):
    """Вписывает картинку в прямоугольник с сохранением пропорций."""
    from PIL import Image
    p = os.path.join(IMG, name)
    iw, ih = Image.open(p).size
    scale = min(w / iw, h / ih)
    nw, nh = int(iw * scale), int(ih * scale)
    return slide.shapes.add_picture(p, x + (w - nw) // 2, y + (h - nh) // 2, nw, nh)


def bg(slide, color=BG_LIGHT):
    return rect(slide, 0, 0, SW, SH, color)


def header(slide, title, kicker=None):
    rect(slide, 0, 0, SW, Inches(0.95), BG_DARK)
    rect(slide, Inches(0.5), Inches(0.36), Inches(0.1), Inches(0.34), ACCENT)
    text(slide, Inches(0.75), Inches(0.18), SW - Inches(1.2), Inches(0.6), title,
         size=26, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF), anchor=MSO_ANCHOR.MIDDLE)
    if kicker:
        text(slide, SW - Inches(3.6), Inches(0.3), Inches(3.1), Inches(0.4), kicker,
             size=13, color=RGBColor(0xAE, 0xC0, 0xD6), align=PP_ALIGN.RIGHT)


def footer(slide, n):
    text(slide, Inches(0.45), SH - Inches(0.42), Inches(9), Inches(0.3),
         "Химическое и биологическое оружие", size=10, color=GREY)
    text(slide, SW - Inches(1.4), SH - Inches(0.42), Inches(1.0), Inches(0.3),
         str(n), size=10, color=GREY, align=PP_ALIGN.RIGHT)


def table(slide, x, y, w, rows, col_w=None, header_fill=ACCENT2, font=12,
          header_font=12, row_h=Inches(0.42), first_col_left=False):
    nr, nc = len(rows), len(rows[0])
    shape = slide.shapes.add_table(nr, nc, x, y, w, row_h * nr)
    tbl = shape.table
    tbl.first_row = True
    if col_w:
        total = sum(col_w)
        for i, cw in enumerate(col_w):
            tbl.columns[i].width = Emu(int(w * cw / total))
    for r in range(nr):
        tbl.rows[r].height = row_h
        for c in range(nc):
            cell = tbl.cell(r, c)
            cell.margin_left = Inches(0.08); cell.margin_right = Inches(0.08)
            cell.margin_top = Inches(0.03); cell.margin_bottom = Inches(0.03)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            if r == 0:
                cell.fill.fore_color.rgb = header_fill
            else:
                cell.fill.fore_color.rgb = RGBColor(0xFF, 0xFF, 0xFF) if r % 2 else LIGHT
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.LEFT if (c == 0 and first_col_left) else PP_ALIGN.LEFT
            run = p.add_run(); run.text = str(rows[r][c])
            f = run.font; f.name = "Calibri"
            f.size = Pt(header_font if r == 0 else font)
            f.bold = (r == 0)
            f.color.rgb = RGBColor(0xFF, 0xFF, 0xFF) if r == 0 else RGBColor(0x22, 0x22, 0x22)
    return tbl


def notes(slide, txt):
    slide.notes_slide.notes_text_frame.text = txt


def content_slide(title, kicker=None, n=None):
    s = prs.slides.add_slide(BLANK)
    bg(s)
    header(s, title, kicker)
    return s


