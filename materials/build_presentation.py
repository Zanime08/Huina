def rect(slide, x, y, w, h, fill):
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    sh.line.fill.background()
    sh.shadow.inherit = False
    return sh


def tb(slide, x, y, w, h, paras):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(0.03)
    tf.margin_top = tf.margin_bottom = 0
    first = True
    for p in paras:
        para = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        para.alignment = p.get("align", PP_ALIGN.LEFT)
        para.space_after = Pt(p.get("space_after", 6))
        para.line_spacing = p.get("line_spacing", 1.15)
        r = para.add_run()
        r.text = str(p.get("text", ""))
        r.font.name = "Calibri"
        r.font.size = Pt(p.get("size", 14))
        r.font.bold = p.get("bold", False)
        r.font.italic = p.get("italic", False)
        r.font.color.rgb = p.get("color", TXT)
    return box


def slide_page(title, kicker=None, n=None):
    s = prs.slides.add_slide(BLANK)
    rect(s, 0, 0, W, H, RGBColor(0xFF, 0xFF, 0xFF))
    rect(s, 0, 0, W, HDR, DARK)
    rect(s, 0.5, 0.30, 0.09, 0.34, ACCENT)
    tb(s, 0.75, 0.15, W - 3.4, 0.62,
       [{"text": title, "size": 25, "bold": True, "color": RGBColor(0xFF, 0xFF, 0xFF),
         "space_after": 0, "line_spacing": 1.0}])
    if kicker:
        tb(s, W - 3.35, 0.28, 2.9, 0.4,
           [{"text": kicker, "size": 12.5, "color": RGBColor(0xA9, 0xBE, 0xD6),
             "align": PP_ALIGN.RIGHT, "space_after": 0, "line_spacing": 1.0}])
    if n:
        tb(s, 0.55, H - 0.42, 8.0, 0.3,
           [{"text": "Химическое и биологическое оружие", "size": 10, "color": GREY,
             "space_after": 0, "line_spacing": 1.0}])
        tb(s, W - 1.35, H - 0.42, 0.85, 0.3,
           [{"text": str(n), "size": 10, "color": GREY, "align": PP_ALIGN.RIGHT,
             "space_after": 0, "line_spacing": 1.0}])
    return s


def col(s, x, w, y=TOP):
    return Stack(s, x, y, w)


def notes(slide, txt):
    slide.notes_slide.notes_text_frame.text = txt


